const DEFAULT_LANG = 'en';

// Danh sách ngôn ngữ hỗ trợ, dùng để build nút chọn ngôn ngữ
const SUPPORTED_LANGS = Object.keys(LOCALES).map((code) => ({
  code,
  name: LOCALES[code].langName,
  flag: LOCALES[code].langFlag,
}));

function t(lang, key, vars = {}) {
  const dict = LOCALES[lang] || LOCALES[DEFAULT_LANG];
  let str = dict[key] ?? LOCALES[DEFAULT_LANG][key] ?? key;
  return str.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
}

function getLang(ctx) {
  return ctx.session?.lang || DEFAULT_LANG;
}

module.exports = { t, getLang, SUPPORTED_LANGS, DEFAULT_LANG };